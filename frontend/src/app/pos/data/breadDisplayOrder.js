const DISPLAY_INDEX = new Map(BREAD_DISPLAY_ORDER.map((id, i) => [id, i]));

/** 알 수 없는 product_id는 맨 뒤로 보낸다(정렬 안정성용 fallback). */
export function getBreadDisplayIndex(productId) {
  return DISPLAY_INDEX.has(productId)
    ? DISPLAY_INDEX.get(productId)
    : Number.MAX_SAFE_INTEGER;
}
